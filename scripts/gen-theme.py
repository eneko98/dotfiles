def arch_mark() -> str:
    """The Arch logo without the trademark sign.

    The shipped SVG is one silhouette path plus two tiny paths that draw the (TM)
    in the bottom-right corner. At the size of a fetch logo that sign is a
    two-pixel speck next to a 250 px mark and reads as dirt, so it is dropped.

    The filter only removes paths whose data starts in that corner (`m23..`,
    `m24..`): if Arch ever redraws the file, the artwork is kept as it is (with
    the sign wherever it landed) instead of the logo losing a piece.
    """
    return re.sub(r'\s*<path\s+d="m2[0-9]{2}[^"]*"\s*/>', "",
                  ARCH_LOGO.read_text())


def zathura_colors(roles: dict[str, str], _ansi: dict[str, str]) -> str:
    """The colours of zathura, as a zathurarc snippet.

    The hand-written zathurarc includes this file, so the PDF viewer speaks the
    same palette as everything else and no hex lives outside theme.lua. The
    chrome is bg1/bg2 with fg text; the selection is the neon at a third of its
    alpha so the page stays readable under it (zathura takes rgba()).
    """
    def rgba(name: str, alpha: float) -> str:
        h = roles[name].lstrip("#")
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        return f'"rgba({r},{g},{b},{alpha})"'

    lines = [
        "# Generated by scripts/gen-theme.py from the active palette.",
        "# Do not edit: edit the palette and re-run the script. Included by",
        "# config/zathura/zathurarc, which keeps only the settings.",
        "",
        f'set default-bg "{roles["bg0"]}"',
        f'set default-fg "{roles["fg0"]}"',
        f'set statusbar-bg "{roles["bg1"]}"',
        f'set statusbar-fg "{roles["fg1"]}"',
        f'set inputbar-bg "{roles["bg2"]}"',
        f'set inputbar-fg "{roles["fg0"]}"',
        f'set completion-bg "{roles["bg1"]}"',
        f'set completion-fg "{roles["fg0"]}"',
        f'set completion-group-bg "{roles["bg0"]}"',
        f'set completion-group-fg "{roles["fg2"]}"',
        f'set completion-highlight-bg "{roles["gold"]}"',
        f'set completion-highlight-fg "{roles["bg0"]}"',
        f'set index-bg "{roles["bg1"]}"',
        f'set index-fg "{roles["fg0"]}"',
        f'set index-active-bg "{roles["gold"]}"',
        f'set index-active-fg "{roles["bg0"]}"',
        f"set highlight-color {rgba("teal", 0.35)}",
        f"set highlight-active-color {rgba("gold", 0.45)}",
        f'set notification-bg "{roles["bg2"]}"',
        f'set notification-fg "{roles["fg0"]}"',
        f'set notification-error-bg "{roles["red"]}"',
        f'set notification-error-fg "{roles["bg0"]}"',
        f'set notification-warning-bg "{roles["gold"]}"',
        f'set notification-warning-fg "{roles["bg0"]}"',
        f'set render-loading-bg "{roles["bg0"]}"',
        f'set render-loading-fg "{roles["fg1"]}"',
        '# Recoloured pages: paper becomes the terminal background, ink the text.',
        f'set recolor-darkcolor "{roles["fg0"]}"',
        f'set recolor-lightcolor "{roles["bg0"]}"',
        "",
    ]
    return "\n".join(lines)


def fetch_logo(roles: dict[str, str], dest: Path) -> None:
    """Write the Arch mark tinted with the palette, as a transparent PNG.

    The source is a flat single-colour silhouette, so the tint is a gradient
    painted through its alpha channel: accent (gold) top-left to neon (teal)
    bottom-right -- the same two-hue idea as the wallpaper. `exclude-chunks`
    keeps the PNG byte-identical between runs, which is what lets --check
    compare it like the text copies instead of guessing from timestamps.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp = Path(tmpdir)
        svg = tmp / "arch.svg"
        base, gradient = tmp / "base.png", tmp / "gradient.png"

        svg.write_text(arch_mark())
        subprocess.run(["magick", "-background", "none", str(svg),
                        "-resize", "256x256", "-depth", "8", str(base)],
                       check=True)
        subprocess.run(["magick", "-size", "256x256", "-depth", "8",
                        f"gradient:{roles['gold']}-{roles['teal']}",
                        str(gradient)], check=True)
        subprocess.run(["magick", str(gradient), str(base), "-alpha", "off",
                        "-compose", "CopyOpacity", "-composite",
                        "-depth", "8",
                        "-define", "png:exclude-chunks=date,time",
                        str(dest)], check=True)


def icon_theme(roles: dict[str, str]) -> str:
    """The Adwaita-* variant whose folder colour matches the accent's hue."""
    red, green, blue = (int(roles["gold"][i:i + 2], 16) / 255 for i in (1, 3, 5))
    hue, _lightness, saturation = colorsys.rgb_to_hls(red, green, blue)
    if saturation < 0.12:
        return "Adwaita-slate"
    degrees = hue * 360
    for start, end, name in ICON_RANGES:
        if start <= degrees < end:
            return f"Adwaita-{name}"
    return "Adwaita-slate"

