# GTK's own Adwaita is compiled in with literal values, so redefining Adwaita's
# names does nothing (measured on GTK3: 473 rules with literal colours, 0
# referencing theme_bg_color). What does work is a user stylesheet, which GTK
# loads at a higher priority: config/gtk-3.0/gtk.css and config/gtk-4.0/gtk.css
# each import a generated copy of this and write their own rules. These are the
# names those rules refer to. GTK4 needs the same file at its own path.
CSS_NAMES = ("bg0", "bg1", "bg2", "fg0", "fg1", "fg2", "gold", "teal", "red")


def css_palette(roles: dict[str, str], _ansi: dict[str, str], where: str) -> str:
    # CSS comments are /* */, not #. The shared GENERATED header would be a parse
    # error, and GTK throws away the whole stylesheet on one, so this writes its
    # own.
    lines = ["/* Generated by scripts/gen-theme.py from the active palette. */"]
    lines.append("/* Do not edit: edit the palette and re-run the script. */")
    lines.append("/*")
    lines.append(f" * The colours {where}/gtk.css imports and its rules use.")
    lines.append(" */")
    lines.append("")
    for name in CSS_NAMES:
        lines.append(f"@define-color {name} {roles[name]};")
    return "\n".join(lines) + "\n"


# Qt's QPalette roles, in enum order. qt6ct stores a colour scheme as three
# comma-separated lists of #AARRGGBB, one per palette group (active, inactive,
# disabled), and the list order is this enum order. 21 entries.
QT_ROLES = (
    "WindowText", "Button", "Light", "Midlight", "Dark", "Mid", "Text",
    "BrightText", "ButtonText", "Base", "Window", "Shadow", "Highlight",
    "HighlightedText", "Link", "LinkVisited", "AlternateBase", "NoRole",
    "ToolTipBase", "ToolTipText", "PlaceholderText",
)


def _argb(hex6: str, alpha: str = "ff") -> str:
    return "#" + alpha + hex6.lstrip("#")


def qt6ct_colors(roles: dict[str, str], _ansi: dict[str, str]) -> str:
    r = roles
    active = {
        "WindowText": r["fg0"], "Button": r["bg2"], "Light": r["fg2"],
        "Midlight": r["bg2"], "Dark": r["bg0"], "Mid": r["bg0"],
        "Text": r["fg0"], "BrightText": r["fg0"], "ButtonText": r["fg0"],
        "Base": r["bg0"], "Window": r["bg1"], "Shadow": "#80000000",
        "Highlight": r["gold"], "HighlightedText": r["bg0"],
        "Link": r["teal"], "LinkVisited": r["teal"],
        "AlternateBase": r["bg2"], "NoRole": r["fg0"],
        "ToolTipBase": r["bg0"], "ToolTipText": r["fg0"],
        "PlaceholderText": r["fg2"],
    }
    inactive = dict(active, **{
        "WindowText": r["fg1"], "Text": r["fg1"], "ButtonText": r["fg1"],
        "BrightText": r["fg1"], "Highlight": r["bg2"], "HighlightedText": r["fg0"],
    })
    disabled = dict(active, **{
        "WindowText": r["fg2"], "Text": r["fg2"], "ButtonText": r["fg2"],
        "BrightText": r["fg2"], "Button": r["bg1"], "Base": r["bg0"],
        "Window": r["bg1"], "Highlight": r["bg2"], "HighlightedText": r["fg2"],
        "Link": r["fg2"], "LinkVisited": r["fg2"], "AlternateBase": r["bg1"],
        "PlaceholderText": r["fg2"],
    })

    def line(mapping: dict[str, str]) -> str:
        out = []
        for role in QT_ROLES:
            value = mapping[role]
            # Shadow is already #aarrggbb; the rest are #rrggbb.
            out.append(value if len(value) == 9 else _argb(value))
        return ",".join(out)

    return (
        "; Generated by scripts/gen-theme.py from the active palette.\n"
        "; Do not edit: edit the palette and re-run the script.\n"
        "[ColorScheme]\n"
        f"active_colors={line(active)}\n"
        f"inactive_colors={line(inactive)}\n"
        f"disabled_colors={line(disabled)}\n"
    )


def gtk_settings(roles: dict[str, str], version: int) -> str:
    lines = [GENERATED, ""]
    lines.append("# Adwaita is compiled into libgtk; gtk.css beside this file is what")
    lines.append("# makes it ours. The icon theme follows the accent.")
    lines.append("[Settings]")
    if version == 3:
        lines.append("gtk-theme-name=Adwaita")
    lines.append("gtk-application-prefer-dark-theme=1")
    lines.append(f"gtk-icon-theme-name={icon_theme(roles)}")
    lines.append(f"gtk-cursor-theme-name={CURSOR}")
    lines.append("gtk-cursor-theme-size=24")
    if version == 3:
        lines.append("gtk-enable-animations=1")
    return "\n".join(lines) + "\n"


