#!/usr/bin/env python3
"""Generate the palette's copies from config/hypr/theme.lua.

theme.lua is the single source of truth for the colours, because Hyprland reads
Lua directly and this repository has one palette, not four. Nothing else reads
Lua, so this script writes the copies the other two consumers need:

    config/kitty/theme.conf   the colours for kitty; kitty.conf includes it
    config/zsh/theme.zsh      the same values as shell variables, for the prompt

Hue values are never written down twice. What *is* written twice, deliberately,
is the meaning: which colour plays which part. That is a decision, not a value,
so it lives in the tables below where it can be read and argued with.

    scripts/gen-theme.py           rewrite both copies
    scripts/gen-theme.py --check   exit non-zero if they are out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PALETTE = ROOT / "config/hypr/theme.lua"

GENERATED = (
    "# Generated by scripts/gen-theme.py from config/hypr/theme.lua.\n"
    "# Do not edit this file: edit the palette and re-run the script.\n"
    "# `scripts/gen-theme.py --check` reports whether this copy is stale.\n"
)

# Which colour does which job, per consumer. theme.lua says what the colours
# *are*; this says what they are *for*.
KITTY = [
    ("background", "bg0"),
    ("foreground", "fg0"),
    ("cursor", "teal"),  # the one element there is always exactly one of
    ("cursor_text_color", "bg0"),
    ("url_color", "teal"),  # links are the other "this is the live thing"
    ("selection_background", "bg2"),  # a surface, so it adds no fourth meaning
    ("selection_foreground", "fg0"),
]

# ANSI order is fixed by the terminal, not by us: 0-7 then the 8 "bright" slots.
ANSI_ORDER = [
    "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
    "bright_black", "bright_red", "bright_green", "bright_yellow",
    "bright_blue", "bright_magenta", "bright_cyan", "bright_white",
]

ASSIGNMENT = re.compile(
    r'^\s*([A-Za-z0-9_]+)\s*=\s*(?:"(#[0-9a-fA-F]{6})"|theme\.([A-Za-z0-9_]+))\s*,?\s*$'
)


def parse_palette(path: Path) -> tuple[dict[str, str], dict[str, str]]:
    """Pull the roles and the ANSI table out of theme.lua.

    Comments go first: theme.lua's prose quotes hex values (the raw extraction
    it started from), and a scanner that reads those would invent colours.
    """
    code = re.sub(r"--.*", "", path.read_text())
    roles: dict[str, str] = {}
    ansi: dict[str, str] = {}
    section: dict[str, str] | None = None

    for line in code.splitlines():
        if "local theme" in line:
            section = roles
            continue
        if "theme.ansi" in line:
            section = ansi
            continue
        match = ASSIGNMENT.match(line)
        if match is None or section is None:
            continue
        name, literal, reference = match.group(1), match.group(2), match.group(3)
        # ansi entries may be aliases (`cyan = theme.teal`), which is how the
        # table stays honest about yellow/gold being one hue
        section[name] = literal if literal else roles[reference]
    return roles, ansi


def kitty_conf(roles: dict[str, str], ansi: dict[str, str]) -> str:
    lines = [GENERATED, ""]
    for option, role in KITTY:
        lines.append(f"{option} {roles[role]}")
    lines.append("")
    for index, name in enumerate(ANSI_ORDER):
        lines.append(f"{'color' + str(index):<7} {ansi[name]}")
    return "\n".join(lines) + "\n"


def zsh_theme(roles: dict[str, str]) -> str:
    lines = [GENERATED, ""]
    lines.append("# The palette as shell variables. Nothing that sources this file")
    lines.append("# contains a hex value of its own.")
    for name, value in roles.items():
        lines.append(f'THEME_{name.upper()}="{value}"')
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    roles, ansi = parse_palette(PALETTE)
    if len(roles) < 9:
        print(f"error: only found {len(roles)} roles in {PALETTE}", file=sys.stderr)
        return 2

    outputs = {
        ROOT / "config/kitty/theme.conf": kitty_conf(roles, ansi),
        ROOT / "config/zsh/theme.zsh": zsh_theme(roles),
    }

    stale: list[Path] = []
    for path, content in outputs.items():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(path)
        if not check:
            path.write_text(content)

    for path in stale:
        print(f"{'stale: ' if check else 'wrote: '}{path.relative_to(ROOT)}")
    if not stale:
        print("up to date")
    return 1 if (check and stale) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
