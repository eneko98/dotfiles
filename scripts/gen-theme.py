def quickshell_theme(roles: dict[str, str], _ansi: dict[str, str],
                      derived: dict) -> str:
    # QML reads neither Lua nor INI, so the bar gets a singleton with the
    # palette as properties. `pragma Singleton` makes it one object shared by
    # every file in the shell; the bar then writes Theme.gold, never a hex.
    #
    # The accent is the one colour the shell repaints at runtime (the album art
    # accent), so it is written as a base value plus a writable copy with a
    # transition. The duration is a literal on purpose: a singleton cannot see
    # Motion by name here (measured).
    lines = ["// Generated by scripts/gen-theme.py from the active palette.",
             "// Do not edit: edit the palette and re-run the script.",
             "pragma Singleton",
             "import QtQuick",
             "",
             "QtObject {"]
    for name in ("bg0", "bg1", "bg2", "fg0", "fg1", "fg2", "gold", "teal", "red"):
        if name == "gold":
            lines.append(f'    readonly property color goldBase: "{roles[name]}"')
            lines.append("    property color gold: goldBase")
            lines.append("")
            lines.append("    Behavior on gold {")
            lines.append("        ColorAnimation { duration: 420; easing.type: Easing.OutCubic }")
            lines.append("    }")
            continue
        lines.append(f'    readonly property color {name}: "{roles[name]}"')

    # The v2 roles: tinted surfaces, state containers, the hover tint and the
    # alphas per region. Nothing reads the colors yet in the greeter (and the
    # bar starts reading them in C3); shipping them early means every reload
    # from now on carries the whole system.
    lines.append("")
    lines.append("    // v2: tinted surfaces (L 0.19/0.21/0.23, the wallpaper's")
    lines.append("    // family hue, a fraction of its chroma).")
    for name in ("s1", "s2", "s3"):
        lines.append(f'    readonly property color {name}: "{derived[name]}"')
    lines.append("")
    lines.append("    // v2: state containers -- the hue of their role, dark and")
    lines.append("    // muted, with a matching text on top.")
    # QML parses any identifier starting with `on` as a signal handler, so
    # the Material-style `onAccentContainer` name is illegal here (measured:
    # "Cannot assign a value to a signal"). The text roles are `textOnAccent`
    # and `textOnNeon` instead.
    for name in ("accentContainer", "textOnAccent",
                 "neonContainer", "textOnNeon"):
        src = {"accentContainer": "accentContainer", "textOnAccent":
               "onAccentContainer", "neonContainer": "neonContainer",
               "textOnNeon": "onNeonContainer"}[name]
        lines.append(f'    readonly property color {name}: "{derived[src]}"')
    lines.append("")
    lines.append("    // v2: hover is a 6% wash of the accent, transitory.")
    lines.append(f'    readonly property color hoverTint: "{derived["hoverTint"]}"')
    lines.append("")
    lines.append("    // v2: how opaque each region's glass must be to hold the")
    lines.append("    // text floors over this wallpaper (0.66..0.96).")
    for name in ("alphaBar", "alphaPanel", "alphaDesk"):
        lines.append(f"    readonly property real {name}:"
                     f" {derived[name]:.2f}")

    lines.append("}")
    return "\n".join(lines) + "\n"


