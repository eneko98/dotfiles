#!/usr/bin/env python3
"""Generate the palette's copies from the active palette.

The active palette is $XDG_STATE_HOME/dotfiles/palette.lua when a wallpaper has
generated one, and config/hypr/theme.lua (the committed default) otherwise.
Hyprland reads it directly; nothing else reads Lua, so this script writes the
copies the other consumers need:

    kitty/theme.conf       the colours for kitty; kitty.conf includes it
    zsh/theme.zsh          the same values as shell variables, for the prompt
    fuzzel/colors.ini      the colours and icon theme for the launcher, included by fuzzel.ini
    yazi/theme.toml        the colours for the file manager
    hypr/hyprlock-theme.conf  hyprlang variables for the lock screen
    mako/theme             the colours for notifications, included by config
    gtk-3.0/palette.css    the names config/gtk-3.0/gtk.css imports
    gtk-4.0/palette.css    the same for GTK4
    gtk-3.0/settings.ini   Adwaita + the icon theme chosen from the accent
    gtk-4.0/settings.ini   the same for GTK4
    qt6ct/colors/theme.conf  Qt's palette, via qt6ct
    qt6ct/qt6ct.conf       Fusion + the same icon theme
    icon-theme             the chosen Adwaita-* variant, read by the wallpaper script
    greeter/regreet.css    the login screen's stylesheet, copied to /etc/greetd
    quickshell/Theme.qml   the palette as a QML singleton, for the bar
    greeter/Theme.qml      the same singleton for the login greeter
    firefox/chrome/palette.css  CSS variables for the Firefox theme
    fetch-logo.png         the Arch mark tinted with the palette, for fastfetch
    zathura/colors         zathurarc colours; the hand-written config includes it

All of them go under $XDG_STATE_HOME/dotfiles/theme/, not into the repository:
the palette follows the wallpaper, and the wallpaper is machine state. install.sh
links each generated file to the fixed path its program expects.

Hue values are never written down twice. What *is* written twice, deliberately,
is the meaning: which colour plays which part. That is a decision, not a value,
so it lives in the tables below where it can be read and argued with.

    scripts/gen-theme.py           rewrite the copies
    scripts/gen-theme.py --check   exit non-zero if they are out of date
"""

